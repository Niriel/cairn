// Collects the licence texts of everything that ships to the browser into
// static/legal/licenses.txt. Run with `pnpm gen:licenses`. The output is
// committed — reproducible from this script, not generated at build time — and
// a Vitest drift guard (src/lib/legal/model/licenses-drift.test.ts) fails when
// it no longer matches node_modules.
//
// Roots: the web app's runtime `dependencies` plus svelte and @sveltejs/kit,
// whose runtime is bundled although they're devDependencies. Each root's
// `dependencies` are followed recursively. Over-including (kit's build-time
// deps) is harmless; under-including would leave a licence notice out.
import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const EXTRA_ROOTS = ['svelte', '@sveltejs/kit'];
const LICENSE_FILE = /^(licen[cs]e|copying)(\.[a-z]+)?$/i;

/**
 * Finds `dep` as Node would from `fromDir`, handling pnpm's layout where a
 * package's dependencies are its siblings under `.pnpm/<name>@<v>/node_modules/`.
 * @param {string} fromDir
 * @param {string} dep
 * @returns {string | null}
 */
function locate(fromDir, dep) {
	for (let dir = fromDir; ; dir = dirname(dir)) {
		const candidate =
			basename(dir) === 'node_modules' ? join(dir, dep) : join(dir, 'node_modules', dep);
		if (existsSync(join(candidate, 'package.json'))) return realpathSync(candidate);
		if (dirname(dir) === dir) return null;
	}
}

/**
 * @param {string} dir
 * @returns {{ name: string, version: string, license?: string, dependencies?: Record<string, string> }}
 */
function readPackage(dir) {
	return JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
}

/**
 * @param {string} dir
 * @returns {string | null}
 */
function licenseText(dir) {
	const file = readdirSync(dir)
		.filter((name) => LICENSE_FILE.test(name))
		.sort()[0];
	if (!file) return null;
	return readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
}

/**
 * @param {string} webDir
 * @returns {string}
 */
export function buildLicensesText(webDir) {
	const root = readPackage(webDir);
	const queue = [...Object.keys(root.dependencies ?? {}), ...EXTRA_ROOTS].map((dep) => ({
		dep,
		from: webDir
	}));
	/** @type {Map<string, { name: string, version: string, license: string, text: string | null }>} */
	const seen = new Map();
	// Directories already read: a package many others depend on is reached once
	// per edge, but its package.json is parsed once. `seen` (by name@version)
	// still decides the output — pnpm can hold one name@version in several
	// directories that differ only by peer-dependency suffix.
	/** @type {Set<string>} */
	const visited = new Set();
	// for…of re-reads the length each step, so it also visits entries pushed
	// during the walk.
	for (const next of queue) {
		const dir = locate(next.from, next.dep);
		if (!dir) {
			console.warn(`gen-licenses: cannot resolve ${next.dep} from ${next.from}; skipped`);
			continue;
		}
		if (visited.has(dir)) continue;
		visited.add(dir);
		const pkg = readPackage(dir);
		const key = `${pkg.name}@${pkg.version}`;
		if (seen.has(key)) continue;
		seen.set(key, {
			name: pkg.name,
			version: pkg.version,
			license: pkg.license ?? 'unknown',
			text: licenseText(dir)
		});
		for (const dep of Object.keys(pkg.dependencies ?? {})) queue.push({ dep, from: dir });
	}
	const entries = [...seen.values()].sort(
		(a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
	);
	const header = [
		'Third-party software shipped with the Cairn web app',
		'',
		'Cairn itself is licensed under AGPL-3.0-or-later (see LICENSE in the source repository).',
		'The packages below are bundled into the app your browser downloads. Each is listed',
		'with its version, its declared licence, and the licence text it ships with.',
		'',
		'Generated by `pnpm gen:licenses` (web/scripts/gen-licenses.mjs). Do not edit by hand.'
	].join('\n');
	const blocks = entries.map(
		(entry) =>
			`==== ${entry.name}@${entry.version} (${entry.license}) ====\n\n` +
			(entry.text ?? `License: ${entry.license} (no licence file shipped with the package)`)
	);
	return `${[header, ...blocks].join('\n\n\n')}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	const webDir = join(dirname(fileURLToPath(import.meta.url)), '..');
	const out = join(webDir, 'static', 'legal', 'licenses.txt');
	const text = buildLicensesText(webDir);
	writeFileSync(out, text);
	console.log(`Wrote ${out} (${text.length} bytes)`);
}
